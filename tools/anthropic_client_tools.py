"""Regenerate the request guard's Anthropic client-tool table from the SDK.

The proxy's restricted-web boundary admits Anthropic tools the caller runs
(custom, bash, text_editor, computer, memory) with exactly the fields the
pinned Anthropic SDK defines for each version, and no server tool. The table
lives inside the standalone guard file (it ships without the SDK); this
script rewrites it from the SDK pinned in uv.lock:

    uv run --extra judge python -m tools.anthropic_client_tools          # write
    uv run --extra judge python -m tools.anthropic_client_tools --check  # compare

A tool family the SDK adds that is in neither list below stops the script:
decide whether the caller or Anthropic runs it before admitting it.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import typing
from pathlib import Path

GUARD = (
    Path(__file__).resolve().parents[1]
    / "src/benchflow/providers/litellm_request_guard.py"
)
BEGIN = "# BEGIN generated by tools/anthropic_client_tools.py"
END = "# END generated by tools/anthropic_client_tools.py"
# Who runs each tool family (Anthropic's tool-use documentation).
CLIENT_FAMILIES = frozenset({"custom", "bash", "text_editor", "computer", "memory"})
SERVER_FAMILIES = frozenset(
    {
        "web_search",
        "web_fetch",
        "code_execution",
        "tool_search_tool_bm25",
        "tool_search_tool_regex",
        "mcp_toolset",
        "advisor",
    }
)


def _literals(annotation: object) -> list[str]:
    found = []
    for arg in typing.get_args(annotation):
        found += [arg] if isinstance(arg, str) else _literals(arg)
    return found


def _family(kind: str) -> str:
    return re.sub(r"_\d{8}$", "", kind)


def table_from(unions, version: str) -> dict[str, object]:
    """The table for the tool params in ``unions`` (the SDK's tool unions)."""
    tools: dict[str, set[str]] = {}
    callers: set[str] = set()
    for union in unions:
        for param in typing.get_args(union):
            hints = typing.get_type_hints(param, include_extras=True)
            for kind in _literals(hints["type"]) or ["custom"]:
                family = _family(kind)
                if family not in CLIENT_FAMILIES | SERVER_FAMILIES:
                    raise SystemExit(
                        f"{param.__name__}: tool family {family!r} is unclassified; "
                        "add it to CLIENT_FAMILIES or SERVER_FAMILIES"
                    )
                if family in CLIENT_FAMILIES:
                    tools.setdefault(kind, set()).update(hints)
                    if "allowed_callers" in hints:
                        callers.update(_literals(hints["allowed_callers"]))
    # A caller that is itself a server tool would run the tool provider-side.
    client_callers = {c for c in callers if _family(c) not in SERVER_FAMILIES}
    return {
        "version": version,
        "custom": tools.pop("custom"),
        "tools": tools,
        "callers": client_callers,
    }


def sdk_table() -> dict[str, object]:
    import anthropic
    from anthropic.types import ToolUnionParam
    from anthropic.types.beta import BetaToolUnionParam

    return table_from((ToolUnionParam, BetaToolUnionParam), anthropic.__version__)


def render(table: dict[str, object]) -> str:
    """The block, already in ruff format's layout (exploded, double quotes)."""

    def fields(names, indent: str) -> list[str]:
        inner = indent + "    "
        return [
            "frozenset(",
            f"{inner}[",
            *(f"{inner}    {json.dumps(name)}," for name in sorted(names)),
            f"{inner}]",
            f"{indent})",
        ]

    tools = typing.cast(dict[str, set[str]], table["tools"])
    custom = fields(table["custom"], "")
    lines = [
        BEGIN,
        f"# from anthropic=={table['version']}; edit the generator, not this block.",
        f"ANTHROPIC_SDK_VERSION = {json.dumps(table['version'])}",
        f"ANTHROPIC_CUSTOM_TOOL = {custom[0]}",
        *custom[1:],
        "ANTHROPIC_CLIENT_TOOLS = {",
    ]
    for kind in sorted(tools):
        body = fields(tools[kind], "    ")
        lines += [f"    {json.dumps(kind)}: {body[0]}", *body[1:-1], body[-1] + ","]
    callers = fields(table["callers"], "")
    lines += ["}", f"ANTHROPIC_CLIENT_CALLERS = {callers[0]}", *callers[1:], END]
    return "\n".join(lines) + "\n"


def current_block(source: str) -> str:
    start = source.index(BEGIN)
    end = source.index(END, start) + len(END) + 1
    return source[start:end]


def main(argv: list[str] | None = None, *, table=None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    source = GUARD.read_text()
    block = render(sdk_table() if table is None else table)
    if args.check:
        if current_block(source) != block:
            print("the guard's Anthropic client-tool table is stale; regenerate it")
            return 1
        return 0
    GUARD.write_text(source.replace(current_block(source), block))
    return 0


if __name__ == "__main__":
    sys.exit(main())
