"""Derive the channel's file closure on checksum-verified pinned CPython.

Run on Linux with --archive naming the x86_64 GNU archive from
_delegate_disarm. The output belongs in _channel_python_files.py. No probe
runs during sandbox preparation: the existing whole-tree proof stays there.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import tempfile
from pathlib import Path

from benchflow.sandbox import _delegate_disarm as stage
from benchflow.sandbox._channel_python_probe import FILE_SOURCE
from benchflow.sandbox._channel_python_probe import import_source as checked_imports
from benchflow.sandbox._exec_channel import HELPER_SOURCE, VERDICT_SOURCE
from benchflow.sandbox._staged_python_layer import TREE_SHA256
from benchflow.sandbox.daytona_channel import _PTY_PRELUDE


def import_source() -> str:
    """Use every helper import, including the PTY and lost-start verdict."""
    return checked_imports((_PTY_PRELUDE, HELPER_SOURCE, VERDICT_SOURCE))


def derive(
    python: Path, root: Path, locale: str = "C.UTF-8"
) -> dict[str, tuple[str, ...]]:
    probe = (
        import_source()
        + FILE_SOURCE
        + r"""
assert sys.prefix == sys.exec_prefix
assert all(path.startswith(sys.prefix + '/') for path in sys.path)
directories = {path for path in sys.path if os.path.isdir(path)}
print(json.dumps(dict(files=sorted(files), directories=sorted(directories))))
"""
    )
    result = subprocess.run(
        [str(python), "-I", "-S", "-B", "-c", probe],
        env={"PATH": "/usr/bin:/bin", "LC_ALL": locale},
        check=True,
        capture_output=True,
        text=True,
        timeout=15,
    )
    return {
        key: tuple(sorted({str(Path(p).relative_to(root)) for p in paths}))
        for key, paths in json.loads(result.stdout).items()
    }


def extract(archive: Path, destination: Path) -> None:
    pin = stage.STAGED_PYTHON_SHA256["x86_64", "gnu"]
    if hashlib.sha256(archive.read_bytes()).hexdigest() != pin:
        raise ValueError("not the pinned channel archive")
    env = dict(os.environ)
    for name in ("TAR_OPTIONS", "POSIXLY_CORRECT"):
        env.pop(name, None)
    subprocess.run(
        [
            "tar",
            "--no-same-owner",
            "--no-same-permissions",
            "-xzf",
            str(archive),
            "-C",
            str(destination),
        ],
        check=True,
        env=env,
        umask=0o022,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, required=True)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as folder:
        root = Path(folder)
        extract(args.archive, root)
        closure = derive(root / "python/bin/python3.12", root)
        pin = stage.STAGED_PYTHON_SHA256["x86_64", "gnu"]
        print(
            '"""Generated by tools/channel_python_files.py; checked by the subset tests."""'
        )
        for key, paths in closure.items():
            print(f"\n{key.upper()}_BY_TREE = {{")
            print(f'    "{TREE_SHA256[pin]}": (')
            for path in paths:
                print(f'        "{path}",')
            print("    ),\n}")
