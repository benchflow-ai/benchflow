"""Write .github/workflows/gate-dispatch.yml from test.yml: the same jobs, on
the self-hosted gate runners, for one commit given by hand.

    python -m tools.ci.gen_gate_dispatch [--check]

GitHub's hosted runners are too small or too few for some of test.yml's jobs on
a release candidate (0.10.0: oracle-parity's 4-CPU task, a 60-minute
deterministic tier at 39%, fresh-resolve's disk), and a pull request must never
reach a self-hosted runner (tests/test_release_automation_workflows.py). So
the release owner runs this workflow by hand (``gh workflow run gate-dispatch.yml
-f sha=<commit>``) on the ephemeral GCE runners labelled by the repository
variable ``BF_GATE_RUNNER`` (without it, GitHub's runner). Its jobs are
test.yml's, step for step; only the trigger, the runner, the commit checked out
and its check differ. ``--check`` exits 1 when the file is not what this writes
(tests/test_gate_dispatch_workflow.py).
"""

from __future__ import annotations

import argparse
import copy
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".github" / "workflows" / "test.yml"
TARGET = ROOT / ".github" / "workflows" / "gate-dispatch.yml"
RUNNER = "${{ vars.BF_GATE_RUNNER || 'ubuntu-24.04' }}"
#: test.yml's early look at the next runner image: not a gate.
LEFT_OUT = ("unit-latest-os",)
CHECKOUT = "actions/checkout@"

HEADER = """\
# GENERATED by tools/ci/gen_gate_dispatch.py from test.yml: do not edit.
# Regenerate with `uv run python -m tools.ci.gen_gate_dispatch`.
#
# test.yml's jobs for one commit, run by hand on the self-hosted gate runners
# (repository variable BF_GATE_RUNNER; GitHub's runner without it). Never on a
# pull request: a pull request must not reach a self-hosted runner.
name: gate-dispatch

on:
  workflow_dispatch:
    inputs:
      sha:
        description: "The full 40-character commit to gate"
        required: true
        type: string

concurrency:
  group: gate-dispatch-${{ inputs.sha }}
  cancel-in-progress: false

permissions:
  contents: read

env:
  HARBOR_TELEMETRY: "off"

"""

CHECK_STEP = {
    "name": "The checked-out commit is the one asked for",
    "env": {"WANT": "${{ inputs.sha }}"},
    "run": (
        "printf '%s\\n' \"$WANT\" | grep -Eqx '[0-9a-f]{40}'\n"
        'test "$(git rev-parse HEAD)" = "$WANT"\n'
    ),
}


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def render() -> str:
    source = yaml.safe_load(SOURCE.read_text())
    jobs = {}
    for name, job in source["jobs"].items():
        if name in LEFT_OUT:
            continue
        job = copy.deepcopy(job)
        job["runs-on"] = RUNNER
        steps = []
        for step in job.get("steps", []):
            steps.append(step)
            if str(step.get("uses", "")).startswith(CHECKOUT):
                step.setdefault("with", {})["ref"] = "${{ inputs.sha }}"
                steps.append(copy.deepcopy(CHECK_STEP))
        if steps:
            job["steps"] = steps
        if "needs" in job:
            needs = [job["needs"]] if isinstance(job["needs"], str) else job["needs"]
            job["needs"] = [n for n in needs if n not in LEFT_OUT]
        jobs[name] = job
    body = yaml.dump(
        {"jobs": jobs}, Dumper=_Dumper, sort_keys=False, width=1000, allow_unicode=True
    )
    return HEADER + _pin_comments(body)


def _pin_comments(body: str) -> str:
    """Each ``uses: …@<sha>`` keeps test.yml's version comment (``# v5.1.0``),
    which YAML drops (tests/test_workflow_action_pinning.py)."""
    comments = dict(_PIN.findall(SOURCE.read_text()))
    return re.sub(
        r"^(\s*(?:- )?uses: (\S+@[0-9a-f]{40}))$",
        lambda m: (
            f"{m.group(1)}  # {comments[m.group(2)]}"
            if m.group(2) in comments
            else m.group(1)
        ),
        body,
        flags=re.M,
    )


_PIN = re.compile(r"uses: (\S+@[0-9a-f]{40})\s+#\s*(\S.*?)\s*$", re.M)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != text:
            print(
                f"{TARGET} is stale: run python -m tools.ci.gen_gate_dispatch",
                file=sys.stderr,
            )
            return 1
        return 0
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
